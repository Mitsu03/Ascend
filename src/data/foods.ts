export const FOOD_BY_ID: Record<string, Food> = Object.fromEntries(FOODS.map((food) => [food.id, food]))

export function getFood(id: string): Food | undefined {
  return FOOD_BY_ID[id]
}

export const CATEGORY_LABELS: Record<FoodCategory, string> = {
  proteina: 'Proteína',
  hidratos: 'Hidratos',
  gordura: 'Gorduras',
  lacticinios: 'Lacticínios',
  fruta: 'Fruta',
  vegetais: 'Vegetais',
  refeicao: 'Refeições',
  snack: 'Snacks',
  bebida: 'Bebidas',
}

/** Normaliza texto para pesquisa (remove acentos e minúsculas). */
export function normalize(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .trim()
}

export function searchFoods(query: string, diet: DietPreference = 'sem_preferencia'): Food[] {
  const q = normalize(query)
  return FOODS.filter((food) => {
    if (diet !== 'sem_preferencia' && !food.diets.includes(diet)) return false
    if (!q) return true
    return normalize(food.name).includes(q) || normalize(CATEGORY_LABELS[food.category]).includes(q)
  })
}
